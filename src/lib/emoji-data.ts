const RECENT_KEY = 'omnivvoice.emoji.recent'

export function loadRecentEmojis(): string[] {
  if (typeof window === 'undefined') return EMOJI_GROUPS[0].emojis
  try {
    const raw = window.localStorage.getItem(RECENT_KEY)
    if (!raw) return EMOJI_GROUPS[0].emojis
    const parsed = JSON.parse(raw) as string[]
    return parsed.length ? parsed.slice(0, 32) : EMOJI_GROUPS[0].emojis
  } catch {
    return EMOJI_GROUPS[0].emojis
  }
}

export function pushRecentEmoji(emoji: string) {
  if (typeof window === 'undefined') return
  const next = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(
    0,
    32
  )
  window.localStorage.setItem(RECENT_KEY, JSON.stringify(next))
}

export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  const all = EMOJI_GROUPS.flatMap((g) => g.emojis)
  // Match by including in label groups loosely — emoji itself or category
  const fromGroups = EMOJI_GROUPS.filter(
    (g) =>
      g.label.toLowerCase().includes(q) ||
      g.id.includes(q) ||
      g.icon === q
  ).flatMap((g) => g.emojis)
  if (fromGroups.length) return Array.from(new Set(fromGroups))
  return all.filter((e) => e.includes(q)).slice(0, 80)
}
